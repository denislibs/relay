// Минификация CSS для продакшен-сборки (build.ts): без комментариев и лишних пробелов, правила — как в исходнике.
// Не через Bun.build: его CSS-сборщик дописывает префиксы под старые браузеры (-moz-, :is → дубли правил) — правил
// становится больше, а разбор дольше. Здесь только то, что не меняет смысла:
//   • комментарии /* … */ — прочь;
//   • любые пробелы и переводы строк — в один пробел;
//   • пробел у { } ; и перед запятой — прочь (там он не значим ни в селекторах, ни в значениях), «;}» → «}».
// Пробел после запятой остаётся: значения своих свойств (--x: a, b) браузер хранит текстом как есть, и их читает JS.
// Пробел у «:» и у комбинаторов не трогаем: «a :hover» и «a:hover» — разные селекторы. Строки в кавычках — как есть.
// Проверка: правила оригинала и результата, разобранные браузером (CSSStyleSheet), совпадают текстом один в один.

const BEFORE = new Set(['{', '}', ';', ',']);   // пробел перед ними не нужен
const AFTER = new Set(['{', '}', ';']);         // и после них

export function minifyCss(src: string): string {
  let out = '';
  let space = false;   // встретились пробелы — решим, нужен ли один, у следующего значимого символа
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '*') {   // комментарий
      const end = src.indexOf('*/', i + 2);
      i = end < 0 ? src.length : end + 1;
      space = true;   // «a/**/b» — два слова, не одно
      continue;
    }
    if (c === ' ' || c === '\n' || c === '\t' || c === '\r' || c === '\f') { space = true; continue; }
    if (space) {
      const prev = out[out.length - 1];
      if (out && !AFTER.has(prev) && !BEFORE.has(c)) out += ' ';
      space = false;
    }
    if (c === '"' || c === "'") {   // строка: до парной кавычки, с экранированием
      let j = i + 1;
      while (j < src.length && src[j] !== c) { if (src[j] === '\\') j++; j++; }
      out += src.slice(i, j + 1);
      i = j;
      continue;
    }
    if (c === '}' && out[out.length - 1] === ';') out = out.slice(0, -1);
    out += c;
  }
  return out;
}
