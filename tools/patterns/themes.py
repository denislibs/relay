def snowflake(cx, cy, r):
    out = []
    for i in range(6):
        a = math.radians(i * 60); ca, sa = math.cos(a), math.sin(a)
        ex, ey = cx + r * ca, cy + r * sa
        out.append(P(f"M{cx} {cy} L{ex:.1f} {ey:.1f}"))
        for t, l in ((0.55, 0.32), (0.8, 0.22)):
            bx, by = cx + r * t * ca, cy + r * t * sa
            for s in (1, -1):
                b = a + s * math.radians(40)
                out.append(P(f"M{bx:.1f} {by:.1f} L{bx + r * l * math.cos(b):.1f} {by + r * l * math.sin(b):.1f}"))
    return out + [C(cx, cy, r * 0.12)]
