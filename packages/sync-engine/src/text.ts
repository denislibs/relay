// Нормализация текста профиля и контактов — так же, как на сервере. Общая для движка и интерфейса.

/** Имя: края обрезаны, внутренние пробелы схлопнуты. */
export const cleanName = (s: string): string => s.trim().replace(/\s+/g, ' ');

/** Многострочный текст (о себе, заметка): переводы строк — \n, края обрезаны. */
export const cleanText = (s: string): string => s.replace(/\r\n?/g, '\n').trim();
